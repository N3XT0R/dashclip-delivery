#!/usr/bin/env bash
#
# Claude Code PreToolUse hook for `git commit`. Blocks the commit (exit 2) when the conditions of
# ADR 0006 and ADR 0009 are not met:
#   1. CHANGELOG.md is not part of the commit, the release pipeline builds it when a version is tagged
#   2. a notable change carries a changelog fragment for the current branch
#   3. fragments only use the six Keep a Changelog types and can be read
#   4. staged PHP files pass Pint

set -uo pipefail

command=$(jq -r '.tool_input.command // empty')
commit_pattern='(^|[;&|[:space:]])git[[:space:]]+([^;&|]*[[:space:]])?commit([[:space:]]|$)'
commit_all_pattern='commit[^;&|]*[[:space:]](-a|--all|-[a-zA-Z]*a[a-zA-Z]*)([[:space:]]|$)'
if [[ ! "$command" =~ $commit_pattern ]]; then
    exit 0
fi

cd "${CLAUDE_PROJECT_DIR:-.}" || exit 0

git_dir=$(git rev-parse --git-dir 2>/dev/null) || exit 0
if [[ -f "$git_dir/MERGE_HEAD" ]]; then
    # A merge brings the fragments of the merged branch along, there is nothing new to record.
    exit 0
fi
branch=$(git symbolic-ref --quiet --short HEAD) || exit 0

# Files the commit will contain: the index, plus tracked changes when the command commits with -a.
committed=$(git diff --cached --name-only --diff-filter=ACMRD)
if [[ "$command" =~ $commit_all_pattern ]]; then
    committed=$(printf '%s\n%s' "$committed" "$(git diff --name-only --diff-filter=ACMRD)" | sort -u)
fi
committed=$(grep -v '^$' <<<"$committed" || true)
if [[ -z "$committed" ]]; then
    exit 0
fi

notable_paths='^(app|bootstrap|config|database|lang|resources|routes|public/build|docker)/|^(composer\.json|composer\.lock|package\.json|package-lock\.json|Dockerfile|docker-compose\.ya?ml)$|^docs/adr/|^\.github/workflows/'
allowed_types='added|changed|deprecated|removed|fixed|security'
fragment=".changes/unreleased/$branch.xml"
skill_hint="Use the changelog skill (/changelog) to write the entry into $fragment and stage it."

errors=()

container_running() {
    docker compose ps --status running --services 2>/dev/null | grep -qx sharing
}

# 1. CHANGELOG.md is generated by the release pipeline only.
if grep -qx 'CHANGELOG.md' <<<"$committed"; then
    errors+=("CHANGELOG.md is part of the commit. It is generated by the release pipeline when a version is tagged; restore it (git restore --staged --worktree CHANGELOG.md) and record the change as a fragment. $skill_hint")
fi

# 2. Notable changes need a fragment for this branch. Release lines (4.x, 4.x-dev) are fed by PRs.
if [[ ! "$branch" =~ ^[0-9]+\.x(-dev)?$ ]] && grep -qE "$notable_paths" <<<"$committed"; then
    if ! git cat-file -e ":$fragment" 2>/dev/null; then
        errors+=("The commit changes application code, configuration or dependencies, but branch '$branch' has no changelog fragment ($fragment) staged or committed. $skill_hint")
    fi
fi

# 3. Fragments must use the six categories only and be readable.
fragments=$(git diff --cached --name-only --diff-filter=ACMR | grep -E '^\.changes/.+\.xml$' || true)
for file in $fragments; do
    invalid=$(git show ":$file" | grep -oE '<change[^>]*>' | grep -vE "type=\"($allowed_types)\"" || true)
    if [[ -n "$invalid" ]]; then
        errors+=("$file uses a change type outside $allowed_types: $invalid")
    fi
done
if [[ -n "$fragments" ]] && container_running; then
    if ! output=$(docker compose exec -T sharing php artisan changelog:generate --dry-run 2>&1); then
        errors+=("The changelog fragments cannot be read: $(tail -n 5 <<<"$output")")
    fi
fi

# 4. PHP files in the commit must pass Pint.
php_files=$(grep -E '\.php$' <<<"$committed" | while read -r file; do [[ -f "$file" ]] && echo "$file"; done)
if [[ -n "$php_files" ]] && container_running; then
    # shellcheck disable=SC2086
    if ! output=$(docker compose exec -T sharing vendor/bin/pint --test $php_files 2>&1); then
        errors+=("Pint reports style issues; run docker compose exec sharing vendor/bin/pint --dirty --format agent and stage the result. $(tail -n 10 <<<"$output")")
    fi
fi

if (( ${#errors[@]} > 0 )); then
    {
        echo "Commit blocked: the project conditions (ADR 0006, ADR 0009) are not met."
        for error in "${errors[@]}"; do
            echo "- $error"
        done
    } >&2
    exit 2
fi

exit 0
